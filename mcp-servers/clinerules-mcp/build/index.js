function extractCrossRefs(body) {
    // Find ".clinerules/NN" or "rule NN" or "Rule NN"
    const refs = new Set();
    const patterns = [
        /\.clinerules\/(\d+(?:-READ-FIRST-\d+)?)/gi,
        /\brule[s]?\s+(\d{1,3})\b/gi,
    ];
    for (const re of patterns) {
        let m;
        while ((m = re.exec(body)) !== null) {
            refs.add(m[1]);
        }
    }
    return Array.from(refs).sort();
}
