// ─── R317 / idea #27100: clinerules_amend_rule ──────────────────────────────
// Ruben 2026-08-16: a reversal logged in the Reversal Log without repairing the
// CAUSAL RULE is cursory window-fixing, not a closed loop. The reversal gate used
// to demand only an RCA bucket + a *claim* of a causal-rule update. This tool is
// the MECHANICAL half: it appends a dated amendment to the rule file ON DISK,
// records the proof in the rule_amend table, and reindexes the MCP index so the
// fix is live everywhere (file -> manifest -> MCP -> FTS) in one call.
function amendRuleOnDisk(slugOrId, taskId, rcaBucket, note, triggerPattern) {
    const row = findRule(slugOrId);
    if (!row) {
        return { ok: false, message: `No rule found for '${slugOrId}'. Use clinerules_lookup or clinerules_search to find the causal rule, then retry.` };
    }
    // Never amend via the MCP DB copy — amend the SOURCE-OF-TRUTH file on disk.
    const filePath = row.path;
    if (!filePath || !fs.existsSync(filePath)) {
        return { ok: false, message: `Rule file for '${row.slug}' not found on disk at ${filePath || "(unknown path)"}.` };
    }
    const body = fs.readFileSync(filePath, "utf-8");
    const ts = new Date().toISOString().replace("T", " ").slice(0, 16) + " UTC";
    const amendment = [
        "",
        "## Amendment (from reversal, " + ts + ")",
        "",
        "**Causal-loop repair:** this rule was amended by clinerules_amend_rule after a within-window reversal",
        `- Task: ${taskId || "(unknown)"}`,
        `- RCA bucket: ${rcaBucket}`,
        `- Trigger pattern: ${triggerPattern.slice(0, 200)}`,
        `- Reversal note: ${note.slice(0, 1000)}`,
        "",
        "The reversal that produced this amendment is closed ONLY because the causal rule text changed.",
        "",
    ].join("\n");
    fs.writeFileSync(filePath, body.replace(/\s+$/, "\n") + amendment, "utf-8");
    // Record durable proof BEFORE reindex so a crash mid-reindex still proves repair.
    try {
        db.prepare(`INSERT INTO rule_amend (rule_id, slug, task_id, rca_bucket, reversal_note, amended_path) VALUES (?,?,?,?,?,?)`).run(row.rule_id, row.slug, taskId || null, rcaBucket.slice(0, 60), note.slice(0, 2000), filePath);
    }
    catch (e) {
        return { ok: false, message: `Rule amended on disk but proof-record failed: ${e.message}. Re-run the tool.` };
    }
    // Live reindex so the MCP + FTS immediately serve the amended text.
    try {
        reindex(db, false);
    }
    catch { /* non-fatal: background reindex will catch up */ }
    return { ok: true, message: `Amended rule ${row.rule_id} (${row.slug}) at ${filePath}, reindexed.`, path: filePath, rule_id: row.rule_id };
}
// RULE 317 AUTO-REPAIR SUPPORT (2026-08-17, Ruben: "the thing that sees the
// correction needs the ability to actually take action and do it"). The validator's
// NOT_REPAIRED gate used to only BLOCK when a window logged a reversal without
// amending the causal rule — four completions in a row logged the flip and never
// repaired, and the rule_amend ledger stayed empty. The gate now extracts every
// causal-rule cite from the flip lines, resolves each against the corpus, and
// amends the cited rule ON DISK on behalf of the stalled window. This helper is
// the extraction half.
function collectFlipCausalCites(revSection) {
    const cited = [];
    const buckets = [];
    const notes = [];
    const flipRe = /\u2192|=>|->|\bbecame\b|\bbecomes\b|\bturned out to be\b|\bwas actually\b|\bcorrected to\b/i;
    const citeRe = /(?:causal\s+rule|rule)\s*(?:updated|amended|fixed)\s*[:\-]?\s*([A-Za-z0-9_.\-]+)|"causal_rule"\s*:\s*"([^"]+)"/i;
    const bucketRe = /(wrong premise|stale assumption|unread source|insufficient probe|scope error)/i;
    const jsonFlipRe = /"initial"\s*:/;
    for (const line of revSection.split("\n")) {
        const t = line.trim();
        if (!t || /no reversals/i.test(t))
            continue;
        const isFlip = flipRe.test(t) || jsonFlipRe.test(t);
        if (!isFlip)
            continue;
        const m = t.match(citeRe);
        if (m) {
            const c = (m[1] || m[2] || "").replace(/\.md$/, "").trim();
            if (c && c !== "idea" && !/#\d/.test(c) && !cited.includes(c))
                cited.push(c);
        }
        const b = t.match(bucketRe);
        if (b && !buckets.includes(b[1].toLowerCase()))
            buckets.push(b[1].toLowerCase());
        if (notes.length === 0 && t.length > 0)
            notes.push(t.slice(0, 180));
    }
    return { cited, buckets, notes };
}
